import Foundation

/// 设置窗口的一级导航：四页，顶部横向分段控件。
///
/// ## 为什么是这四页
///
/// **「搜索」和「搜索来源」回答的是同一个问题**——「去哪儿搜」：
///
/// * 搜索页给出本机范围（整台 Mac / 指定文件夹）；
/// * 来源页给出网络位置（哪几台 NAS、哪几个共享）。
///
/// 用户想的是「我要搜这几个地方」，而不是「先想清楚这是本地还是网络」。
/// 分成两页的结果是：加了一台 NAS 之后，得跳到另一页才能调整搜索行为；
/// 判断「为什么搜不到」时也要在两页之间来回看。合并成一页后，
/// **「搜什么」集中在一处**，剩下的三页职责清晰：
///
/// * **通用** —— 应用怎么启动、快捷键、权限；
/// * **搜索** —— 搜哪些地方、怎么显示结果；
/// * **AI** —— 允许 AI 用不用、能用哪些位置、助手在不在跑、历史怎么清；
/// * **高级** —— 诊断与实验性开关。
///
/// ## 「AI」为什么必须是一级页（2026-10-22 拍板）
///
/// 1.1.2 唯一的新增主功能就是 MCP，而它原先挂在「高级」里（§14.3.1 记过这条
/// 冲突）。后果是：用户装完新版要开 AI，得先想到去「高级」翻；而「高级」本该
/// 只放诊断与实验性开关，塞进一个正式功能之后，它退化成了杂物抽屉。
///
/// 反过来，AI 页也不能再拆细：开关、来源授权、助手状态、历史清理回答的是同一个
/// 问题——「AI 现在能做什么、我给它开了什么」，拆成两页会让「为什么搜不到」
/// 又要在两页之间对照（与「搜索来源」并入「搜索」同一条理由）。
///
/// 放在 Core 而不是 App 层，是因为 App 层是 `executableTarget`、测试目标
/// import 不到，而「最多四页、不含权限/外观/关于/搜索来源」这条契约值得被测试锁住。
///
/// 四页的排列顺序就是这里的声明顺序——视图直接遍历 `allCases`，
/// 不另建一份顺序表。
public enum SettingsPane: String, CaseIterable, Identifiable, Sendable {
    case general = "通用"
    case search = "搜索"
    case ai = "AI"
    case advanced = "高级"

    public var id: String { rawValue }
}

/// 设置窗口标题。
///
/// 按 macOS 惯例：窗口叫「设置」，页面名由标题栏承担——
/// 标题里再写一遍产品名就跟页面名重复了。
public enum SettingsWindowTitle {
    public static let text = "设置"
}
